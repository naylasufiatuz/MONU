-- 1. Buat Tabel Data Sensor (Telemetri IoT)
create table if not exists public.sensor_readings (
    id bigint generated by default as identity primary key,
    device_id text not null default 'monu-node-1',
    device_name text default 'ESP32 MONU Node',
    temperature numeric,
    humidity numeric,
    soil_moisture_raw numeric,
    soil_moisture_percent numeric,
    mq2_raw numeric,
    thermocouple numeric,
    relay_active boolean default false,
    pump_active boolean default false,
    wifi_connected boolean default true,
    ip_address text,
    device_status text default 'online',
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Indeks untuk query cepat berdasarkan device_id & created_at
create index if not exists idx_sensor_readings_device_created 
    on public.sensor_readings (device_id, created_at desc);

-- 2. Aktifkan Row Level Security (RLS) & Berikan Izin Publik/Anon
alter table public.sensor_readings enable row level security;

-- Izinkan SELECT (baca data untuk Mobile App & Web Dashboard)
create policy "Allow read access for all"
    on public.sensor_readings for select
    using (true);

-- Izinkan INSERT (kirim data dari ESP32, Mobile App, atau Web)
create policy "Allow insert access for all"
    on public.sensor_readings for insert
    with check (true);

-- 3. Aktifkan Realtime Publikasi untuk Tabel sensor_readings
-- (Supaya aplikasi HP dan Website langsung update otomatis tanpa reload)
alter publication supabase_realtime add table public.sensor_readings;

-- 4. Tabel Riwayat Diagnosa AI (Opsional: Simpan Rekomendasi AI Gemini)
create table if not exists public.ai_consultations (
    id bigint generated by default as identity primary key,
    device_id text not null default 'monu-node-1',
    prompt text not null,
    response text not null,
    model text default 'gemini-flash-latest',
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.ai_consultations enable row level security;
create policy "Allow read ai for all" on public.ai_consultations for select using (true);
create policy "Allow insert ai for all" on public.ai_consultations for insert with check (true);
